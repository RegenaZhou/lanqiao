/*
问题描述
小蓝正在测试三台由 AI 控制的机器人。三台机器人位于同一条直线上，当前位置分别为 A,B,C，两个位置之间的距离为它们坐标之差的绝对值。

小蓝可以选择一台机器人，让它向左或向右移动不超过 K 个单位距离，也可以不进行移动。移动后的坐标必须是整数，机器人之间允许重合。

小蓝希望移动后，三台机器人两两之间的距离之和尽可能小。

现在，请你帮助小蓝计算，这个距离之和最小是多少。

输入格式
第一行包含一个整数 Q（1≤Q≤2×10^5），表示测试组数。

接下来 Q 行，每行包含四个整数 A,B,C,K（0≤A,B,C,K≤10^9），分别表示三台机器人的初始位置和最多允许移动的距离。

移动后的坐标不受输入坐标范围限制。

输出格式
输出 Q 行，每行一个整数，表示对应测试中三台机器人两两距离之和的最小值。

样例输入
3
0 4 10 3
0 4 10 10
2 2 2 5

样例输出
14
8
0

样例说明
第一组测试中，可以将位置为 10 的机器人移到 7。三台机器人的位置为 0,4,7，两两距离之和为 4+7+3=14，这是最小值。

第二组测试中，可以将位置为 10 的机器人移到 4，两两距离之和为 4+4+0=8。

第三组测试中，三台机器人已经位于同一位置，不需要移动。*/
#include <iostream>
#include <algorithm>
using namespace std;
using ll = long long;
int arr[3], k;
void solve()
{
    cin >> arr[0] >> arr[1] >> arr[2] >> k;
    sort(arr, arr + 3);
    int b1 = arr[1] - arr[0], b2 = arr[2] - arr[1];
    if (b1 > b2) swap(b1, b2);
    ll ans = 2 * b1 + (k < b2 ? 2 * (b2 - k) : 0);
    cout << ans << '\n';
}
int main()
{
    ios::sync_with_stdio(0), cin.tie(0), cout.tie(0);
    int q;
    cin >> q;
    while (q--)
    {
        solve();
    }
    return 0;
}
