/*
问题描述
小蓝准备抽取一些图片，测试 AI 的图片识别能力。图片分别存放在 N 个文件夹中，第 i 个文件夹有 Ai 张图片，各文件夹中的图片都已排好顺序。

小蓝可以从每个文件夹中取出前若干张图片，也可以不取。他希望一共取出 K 张图片，并且恰好有 M 个文件夹被取过图片。

现在，请你帮助小蓝计算，满足要求的取图方案共有多少种。两种方案只要有一个文件夹取出的图片数量不同，就视为不同的方案。答案对 998244353 取模。

输入格式
第一行包含三个整数 N,M,K（1≤N≤60，0≤M≤N，0≤K≤2000），分别表示文件夹数量、需要取图的文件夹数量和需要取出的图片总数。

第二行包含 N 个整数 A1,A2,…,AN（0≤Ai≤2000），其中 Ai 表示第 i 个文件夹中的图片数量。

输出格式
输出一个整数，表示满足要求的取图方案数对 998244353 取模后的结果。如果不存在符合要求的方案，输出 0。

样例输入
3 2 3
1 2 3

样例输出
4

样例说明
三个文件夹各取出的图片数量可以为：

第一个文件夹	第二个文件夹	第三个文件夹
1				2				0
1				0				2
0				1				2
0				2				1
每种方案都恰好从两个文件夹中取图，且一共取出三张，因此答案为 4。*/