/*
问题描述
小蓝正在用图片测试 AI 的识别效果。选定 n 张互不相同的图片后，小蓝会改变这些图片的排列顺序，将每一种排列分别作为一组测试数据。

为了分批进行测试，小蓝需要将所有测试数据平均分成 B^E 份。每份包含的测试数据组数必须相同，且不能有空份。其中， B^E 表示 E 个 B 相乘。

现在，请你帮助小蓝计算，最少需要选取多少张图片，才能满足分组要求。共有 Q 种独立的分组要求，每种要求给出两个整数 B,E。

输入格式
第一行包含一个整数 Q（1≤Q≤2000），表示分组要求的数量。

接下来 Q 行，每行包含两个整数 B,E（2≤B≤10^9，1≤E≤10^9）。

输出格式
输出 Q 行，每行一个整数，表示满足对应分组要求时，最少需要选取的图片数量。

样例输入
4
12 1
12 2
7 2
2 3

样例输出
4
6
14
4

样例说明
第一种要求需要平均分成 12 份。选取 3 张图片时只有 6 种排列，无法分组；选取 4 张图片时有 24 种排列，可以分为 12 份，每份 2 组，因此答案为 4。

第二种要求需要平均分成 144 份。选取 5 张图片时有 120 种排列，不符合要求；选取 6 张图片时有 720 种排列，可以分为 144 份，每份 5 组，因此答案为 6。*/