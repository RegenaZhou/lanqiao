#include <iostream>
#include <string>
using namespace std;
using ll = long long;
int main()
{
    ios::sync_with_stdio(0), cin.tie(0), cout.tie(0);
    ll m, N;
    string a0, a1, a2, b;
    ll cnt0 = 0, cnt1 = 0, cnt2 = 0, cnt3 = 0;
    cin >> m >> N;
    cin.ignore();

    getline(cin, a0);
    getline(cin, a1);
    getline(cin, a2);
    getline(cin, b);

    for (int i = 0; i < m; i++)
    {
        if (a0[i] == '0') cnt0++;
        if (a1[i] == '0') cnt1++;
        if (a2[i] == '0') cnt2++;
    }

    ll tmp = 0;
    for (int i = 0; i < m; i++)
    {
        tmp = 0;
        if (a0[i] == '1') tmp++;
        if (a1[i] == '1') tmp++;
        if (a2[i] == '1') tmp++;
        if (b[i] == '1') tmp++;
        if (tmp % 2 == 0) cnt3++;
    }

    ll ans, ans1 = 0, ans2 = 0, zs, ys;
    zs = N / 4, ys = N % 4;
    if (cnt0 == m) ans1++;
    if (ys == 1) ans2 = ans1;
    if (cnt1 == m) ans1++;
    if (ys == 2) ans2 = ans1;
    if (cnt2 == m) ans1++;
    if (ys == 3) ans2 = ans1;
    if (cnt3 == m) ans1++;

    ans = (zs * ans1 + ans2) % (ll)998244353;

    cout << ans << '\n';

    return 0;
}