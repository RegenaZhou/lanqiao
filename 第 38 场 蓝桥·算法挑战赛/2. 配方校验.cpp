/*
问题描述
小蓝正在测试一套配方校验系统。系统中共有 m 种配料，每份配方中各种配料的数量均为非负整数。

校验时，同一种配料需要两份一组进行配对。系统并不关心某种配料具体有多少份，只关心它是否会留下无法配对的一份。
因此，一份配方可以用一个长度为 m 的 01 串表示：第 j 位为 0，表示第 j 种配料可以全部配对；第 j 位为 1，表示第 j 种配料会剩下一份。若一份配方的状态全为 0，则称它通过校验。

系统已经记录了前三份配方，编号分别为 1,2,3。从第 4 份配方开始，系统会根据前三份配方和一份固定的基础配方生成新的记录。

具体来说，设第 i 份配方的记录为 Ai ，基础配方的记录为 B，则对于所有 i≥4，都有：Ai=Ai−1⊕Ai−2⊕Ai−3⊕B 其中⊕ 表示按位异或。
将多份配方混合时，同种配料的数量会相加，因此其奇偶状态可以通过异或得到。

给定正整数 N，请你计算前 N 份配方中有多少份通过校验。由于答案可能很大，你只需要输出答案对 998244353 取模后的结果。

输入格式
第一行包含两个整数 m,N（1≤m≤2×10^5，1≤N≤10^18），分别表示配料种数以及需要统计的配方数量。

接下来四行，每行包含一个长度为 m 的 01 串，依次表示 A1,A2,A3 和基础配方 B。

输出格式
输出一个整数，表示前 N 份配方中通过校验的配方数量对 998244353 取模后的结果。

样例输入
3 12
100
010
001
111

样例输出
3

样例说明
前 12 份配方的记录依次为：100,010,001,000,100,010,001,000,100,010,001,000

其中第 4,8,12 份配方通过校验，因此答案为 3。*/
#include <iostream>
#include <string>
using namespace std;
using ll = long long;
int main()
{
    ios::sync_with_stdio(0), cin.tie(0), cout.tie(0);
    ll m, N;
    string a0, a1, a2, b;
    ll cnt0 = 0, cnt1 = 0, cnt2 = 0, cnt3 = 0;
    cin >> m >> N;
    cin.ignore();

    getline(cin, a0);
    getline(cin, a1);
    getline(cin, a2);
    getline(cin, b);

    for (int i = 0; i < m; i++)
    {
        if (a0[i] == '0') cnt0++;
        if (a1[i] == '0') cnt1++;
        if (a2[i] == '0') cnt2++;
    }

    ll tmp = 0;
    for (int i = 0; i < m; i++)
    {
        tmp = 0;
        if (a0[i] == '1') tmp++;
        if (a1[i] == '1') tmp++;
        if (a2[i] == '1') tmp++;
        if (b[i] == '1') tmp++;
        if (tmp % 2 == 0) cnt3++;
    }

    ll ans, ans1 = 0, ans2 = 0, zs, ys;
    zs = N / 4, ys = N % 4;
    if (cnt0 == m) ans1++;
    if (ys == 1) ans2 = ans1;
    if (cnt1 == m) ans1++;
    if (ys == 2) ans2 = ans1;
    if (cnt2 == m) ans1++;
    if (ys == 3) ans2 = ans1;
    if (cnt3 == m) ans1++;

    ans = (zs * ans1 + ans2) % (ll)998244353;

    cout << ans << '\n';

    return 0;
}
