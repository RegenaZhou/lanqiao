/*
问题描述
暑假集训期间，教练安排了 N 个训练任务，按顺序排成一列，编号为 1,2,…,N。第 i 个任务的难度为 Ai。

现在教练想让每一个位置都作为一次分界点来进行评估。

当选择位置 P 作为分界点时，定义：

左边任务的完成时间为 L(P)=∑1≤i<P(Ai×(P−i))

右边任务的完成时间为 R(P)=∑P<i≤N(Ai×(i−P))

位置 P 的完成差时定义为：∣L(P)−R(P)∣

请你对每一个 P=1,2,…,N，输出它的完成差时。

输入格式
第一行输入一个整数 N(1≤N≤10^5)，表示任务数量。

第二行输入 N 个整数 A1,A2,…,AN(1≤Ai≤10^6)，表示每个任务的难度。

输出格式
输出一行 N 个整数，第 i 个整数表示当 P=i 时的完成差时。

样例输入
5
1 3 2 4 1

样例输出
23 12 1 10 21

样例说明
当 P=1 时，左边没有任务，右边完成时间为 3×1+2×2+4×3+1×4=23 ，所以完成差时为 23。

当 P=3 时，左边完成时间为 1×2+3×1=5，右边完成时间为 4×1+1×2=6，所以完成差时为 1。

其余位置同理。*/