/*
问题描述
蓝桥学院将举办一场程序设计 PK 赛，共有 n 支参赛队，队伍编号为 1∼n。

赛前，组委会按报名顺序把队伍编号写在一块长度为 n 的展示板上，第 i 个位置写的是 i，即初始展示板为 [1,2,…,n]。

为了增加悬念，组委会对展示板做了若干次 "循环右移"。每次循环右移，是把最后一个位置的编号移到最前面，其余编号依次向右移动一位。

比赛当天，工作人员只看清了一条信息：移位完成后，第 p 个位置上的编号是 v。

请你根据这条信息，还原并输出移位完成后展示板的完整样子。

输入格式
输入一行，包含三个整数 n,p,v（1≤n≤10^3，1≤p,v≤n），分别表示参赛队数量、已知位置和该位置上的编号。

输出格式
输出一行，包含 n 个整数，表示移位完成后的展示板，相邻两个整数之间用一个空格隔开。

样例输入
5 2 5

样例输出
4 5 1 2 3*/
#include <iostream>
using namespace std;
int main()
{
    ios::sync_with_stdio(0), cin.tie(0), cout.tie(0);
    int n, p, v;
    cin >> n >> p >> v;
    v = (v + n + 1 - p) % n;
    if (v == 0) v = n;
    cout << v;
    for (int i = 1; i < n; i++)
    {
        if (v == n) v = 0;
        v++;
        cout << " " << v;
    }
    return 0;
}
